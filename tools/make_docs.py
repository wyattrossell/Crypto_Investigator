"""
Generate the validation documentation set for the current version.

Usage:  python tools/make_docs.py     (from the project root)

Writes two PDFs to docs/validation/:

1. v{VERSION}-technical-validation.pdf
   The full methodology document: architecture, data sources, algorithms,
   integrity controls, and verification procedures, written so an outside
   expert can examine and independently validate the software for court.

2. v{VERSION}-overview.pdf
   The 30,000-foot companion: what the tool does, what it refuses to do,
   and how to install and run it.

Numbers (thresholds, caps, defaults) are pulled live from app.config so
the documents can never silently drift from the code they describe. The
technical document also embeds the SHA-256 of this version's complete
source listing, giving reviewers a fixed integrity anchor.
"""

import hashlib

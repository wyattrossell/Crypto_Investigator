PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (PageBreak, Paragraph, SimpleDocTemplate,
                                Spacer, Table, TableStyle)

import make_listing
from app import config

OUTPUT_DIR = PROJECT_ROOT / "docs" / "validation"
PAGE_MARGIN = 0.8 * inch


def _styles():
    base = getSampleStyleSheet()
    return {
        "title": base["Title"],
        "h1": base["Heading1"],
        "h2": base["Heading2"],
        "body": ParagraphStyle("vbody", parent=base["BodyText"],
                               spaceAfter=6, leading=13),
        "bullet": ParagraphStyle("vbullet", parent=base["BodyText"],
                                 leftIndent=16, spaceAfter=3, leading=13),
        "small": ParagraphStyle("vsmall", parent=base["BodyText"],
                                fontSize=8, leading=10),
        "mono": ParagraphStyle("vmono", parent=base["BodyText"],
                               fontName="Courier", fontSize=8, leading=10),
    }


def _kv_table(rows, styles):
    data = [[Paragraph(f"<b>{k}</b>", styles["small"]),
             Paragraph(str(v), styles["small"])] for k, v in rows]
    table = Table(data, colWidths=[1.9 * inch, 5.0 * inch])
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b7c1cc")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 0), (-1, -1),
         [colors.white, colors.HexColor("#f5f8fa")]),
    ]))
    return table


def _add(story, styles, heading, paragraphs, level="h1"):
    """Append a heading and its body. Strings starting '• ' are bullets."""
    if heading:
        story.append(Paragraph(heading, styles[level]))
    for text in paragraphs:
        style = styles["bullet"] if text.startswith("• ") else styles["body"]
        story.append(Paragraph(text, style))


def _listing_hash() -> tuple:
    """(relative path, sha256) of the current version's source listing,
    regenerating it first so the hash matches the code as it stands."""
    make_listing.main()
    listing = (PROJECT_ROOT / "docs" / "listings" /
               f"v{config.APP_VERSION}-full-listing.txt")
    digest = hashlib.sha256(listing.read_bytes()).hexdigest()
    return (f"docs/listings/{listing.name}", digest)



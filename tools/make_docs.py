def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    listing_rel, listing_sha = _listing_hash()

    validation_path = (OUTPUT_DIR /
                       f"v{config.APP_VERSION}-technical-validation.pdf")
    build_validation(validation_path, generated, listing_rel, listing_sha)
    print(f"Wrote {validation_path}")

    overview_path = OUTPUT_DIR / f"v{config.APP_VERSION}-overview.pdf"
    build_overview(overview_path, generated)
    print(f"Wrote {overview_path}")


if __name__ == "__main__":
    main()

def _custody_csv(custody_entries: list) -> str:
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=[
        "id", "trace_id", "source", "url", "http_status", "sha256",
        "from_cache", "fetched_utc"])
    writer.writeheader()
    writer.writerows(custody_entries)
    return buffer.getvalue()


def build_evidence_package(zip_path: str, case: dict, trace_row: dict,
                           result: dict, custody_entries: list,
                           agency: dict, annotations: dict,
                           work_dir) -> list:
    """Assemble the disclosure ZIP. Returns the manifest rows
    [(filename, sha256, description)]. `work_dir` is a Path for the
    intermediate PDF files."""
    trace_id = trace_row["id"]
    files = []      # (arcname, bytes, description)

    # 1. Court report PDF.
    report_path = work_dir / f"trace_{trace_id}_report.pdf"
    pdf_report.build_report(str(report_path), case, trace_row, result,
                            custody_entries, annotations=annotations)
    files.append((f"fund_tracing_report_trace{trace_id}.pdf",
                  report_path.read_bytes(),
                  "Court-ready fund-tracing report"))

    # 2. Chain-of-custody CSV (complete log).
    files.append((f"chain_of_custody_trace{trace_id}.csv",
                  _custody_csv(custody_entries).encode("utf-8"),
                  "Complete chain-of-custody log (every data pull: URL, "
                  "UTC time, SHA-256 of raw response)"))

    # 3. Raw trace data.
    files.append((f"trace_{trace_id}_raw.json",
                  json.dumps(result, indent=1).encode("utf-8"),
                  "Complete machine-readable trace result"))

    # 4. Affidavit methodology draft.
    files.append((f"DRAFT_affidavit_methodology_trace{trace_id}.txt",
                  affidavit_text(case, trace_row, result,
                                 len(custody_entries),
                                 agency).encode("utf-8"),
                  "DRAFT affidavit methodology paragraphs (counsel to "
                  "adapt)"))

    # 5. Traceroute + DRAFT freeze letter per exit.
    for index, exit_entry in enumerate(result.get("exits") or [],
                                       start=1):
        safe_entity = "".join(
            ch if ch.isalnum() else "_"
            for ch in exit_entry["entity"])[:40] or "exit"
        if exit_entry.get("path"):
            files.append((
                f"traceroute_{index}_{safe_entity}.txt",
                traceroute_text(result, exit_entry,
                                trace_id).encode("utf-8"),
                f"Hop-by-hop fund-flow path to {exit_entry['entity']}"))
        address = exit_entry["address"]
        node = next((n for n in result["nodes"]
                     if n["address"] == address), None)
        funding_edges = [e for e in result["edges"]
                         if e["to_address"] == address
                         or e["from_address"] == address]
        if node and funding_edges:
            letter_path = work_dir / f"freeze_{trace_id}_{index}.pdf"
            entity = exit_entry["entity"]
            freeze_letter.build_freeze_request(
                str(letter_path), case, result, address, node,
                funding_edges, entity,
                label_store.custodian_lookup(entity),
                label_store.compliance_lookup(entity), agency)
            files.append((
                f"DRAFT_freeze_request_{index}_{safe_entity}.pdf",
                letter_path.read_bytes(),
                f"DRAFT preservation/freeze request to "
                f"{exit_entry['entity']}"))

    # Manifest with hashes, then the ZIP itself.
    manifest_rows = [(name, hashlib.sha256(content).hexdigest(),
                      description) for name, content, description in files]
    manifest_lines = [
        f"EVIDENCE PACKAGE MANIFEST - {config.APP_NAME} "
        f"v{config.APP_VERSION}",
        f"Case: {case['name']}"
        + (f" ({case['case_number']})" if case.get("case_number") else ""),
        f"Trace: #{trace_id} ({result['chain']}, "
        f"{result.get('direction', 'forward')})",
        f"Generated: {_now_utc()}",
        "",
        "Files (SHA-256 of each file as packaged):",
        "",
    ]
    for name, digest, description in manifest_rows:
        manifest_lines += [name, f"  SHA-256: {digest}",
                           f"  {description}", ""]
    manifest_lines.append(
        "Verify any file by recomputing its SHA-256 and comparing with "
        "this manifest. DRAFT documents require review by the "
        "prosecuting authority before service.")

    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as bundle:
        bundle.writestr("MANIFEST.txt", "\n".join(manifest_lines))
        for name, content, _description in files:
            bundle.writestr(name, content)
    return manifest_rows
